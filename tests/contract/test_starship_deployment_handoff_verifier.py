def digest(value):
    return sha256(json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()).hexdigest()


def seal(study):
    handoff = study["handoff"]
    handoff["handoff_sha256"] = digest({k: v for k, v in handoff.items() if k != "handoff_sha256"})
    study["prediction"]["deployment_handoff"]["handoff_sha256"] = handoff["handoff_sha256"]


def reseal_history(study):
    history, last, generation = [], None, 0
    for entry in study["trace"]:
        if entry["kind"] == "command":
            history.append(deepcopy(entry))
            generation += 1
            continue
        row = entry["row"]
        current = {"kind": "observation", **{k: row[k] for k in ("time_s", "released_count", "sequencer_state")}}
        if current == last:
            continue
        if last is not None and any(current[k] != last[k] for k in ("released_count", "sequencer_state")):
            generation += 1
        history.append(current)
        last = current
    study["handoff"].update(history=history, generation=generation)
    study["prediction"]["deployment_handoff"]["generation"] = generation
    seal(study)


def director_record(before, later, action, point="deployment_monitor"):
    return {"clock_id": "ship", "request": {"point": point, "observation": deepcopy(before)},
            "dispatch": {"action": action, "time_s": before["time_s"], "observation": deepcopy(before)},
            "later_observation": deepcopy(later)}


def persist(study, forecast):
    raw = (json.dumps(forecast, indent=2, allow_nan=False)+"\n").encode()
    study["prediction"]["prediction_sha256"] = sha256(raw).hexdigest()
    return raw


