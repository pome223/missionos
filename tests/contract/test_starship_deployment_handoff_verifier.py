@pytest.mark.parametrize("missing_resume_event", [False, True])
def test_same_tick_command_is_after_observation_and_hold_resume_prefix_matches(records, missing_resume_event):
    study, _, raw = records
    def observation(time_s, sequence):
        return {"kind": "observation", "row": {"time_s": time_s, "released_count": 0,
                "sequencer_state": sequence, "phase": "orbital_coast", "release_acknowledged": False}}
    prefix = [observation(984., "running"), observation(986., "running"),
              {"kind": "command", "time_s": 986., "action": "hold"}, observation(988., "held"),
              observation(989., "held"), {"kind": "command", "time_s": 989., "action": "continue"}]
    study["trace"] = prefix+study["trace"]
    events = study["deployment_run"]["events"]
    events[1:1] = [{"event": "managed_mission_command", "point": "deployment_start", "time_s": 986., "action": "hold"},
                  {"event": "managed_mission_command", "point": "deployment_reassessment", "time_s": 989., "action": "continue"},
                  {"event": "managed_deployment_resumed", "time_s": 989.}]
    current = study["deployment_run"]["mission_director"]["records"]
    study["deployment_run"]["mission_director"]["records"] = [
        director_record(prefix[1]["row"], prefix[3]["row"], "hold", "deployment_start"),
        director_record(prefix[4]["row"], study["trace"][6]["row"], "continue", "deployment_reassessment"), *current]
    reseal_history(study)
    if missing_resume_event:
        events[:] = [e for e in events if e["event"] != "managed_deployment_resumed"]
    assert verify(study, raw)["passed"] is not missing_resume_event


